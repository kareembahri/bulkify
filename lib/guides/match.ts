const BY_MUSCLE: Record<string, string> = {
  chest: 'benchPress', back: 'bentRow', shoulders: 'overheadPress', biceps: 'curl', triceps: 'pushdown', forearms: 'wristCurl',
  quads: 'squat', hamstrings: 'hinge', glutes: 'hipThrust', calves: 'calfRaise', abs: 'crunch', traps: 'shrug', full_body: 'burpee', cardio: 'run',
};

const toKey = (s: string) => s.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');

function equipFor(key: string, equipment: string): Equip {
  if (/ez-bar/.test(key)) return 'ezbar';
  if (/medicine-ball|wall-ball|ball-slam/.test(key)) return 'medball';
  if (/plate-pinch/.test(key)) return 'plate';
  if (/sandbag/.test(key)) return 'sandbag';
  if (/trap-bar|farmer-s-walk-bar/.test(key)) return 'barbell';
  if (/farmer-s-walk$/.test(key)) return 'dumbbell';
  if (/sled|prowler|treadmill|bike|rowing|elliptical|stair|skierg|trainer|versaclimber/.test(key)) return 'machine';
  const known: Equip[] = ['barbell', 'dumbbell', 'kettlebell', 'cable', 'machine', 'smith', 'bodyweight', 'other'];
  if (equipment === 'bands') return 'band';
  return (known as string[]).includes(equipment) ? (equipment as Equip) : 'other';
}

/** The movement for an exercise: always returns one (custom exercises fall back by name, then by muscle). */
export function movementFor(ex: { slug?: string | null; name_en?: string | null; equipment: string; primary_muscle: string }): Movement & { matched: boolean } {
  const key = toKey(ex.slug || ex.name_en || '');
  const equip = equipFor(key, ex.equipment);
  for (const [re, pattern, opts = {}, hold] of RULES) {
    if (re.test(key)) {
      const o = { ...opts };
      let h: Hold | undefined = hold;
      if (o.hold) { h = o.hold; }
      // weights on the back for barbell/smith versions of standing lifts
      if (!h && (equip === 'barbell' || equip === 'smith') && ['calfRaise', 'lunge', 'stepUp', 'bulgarian'].includes(pattern) && !o.seated) { h = 'back'; o.hold = 'back'; }
      if (pattern === 'calfRaise' && o.seated) { h = equip === 'machine' ? 'none' : 'hips'; }
      if (!h && equip === 'kettlebell' && pattern === 'squat' && !o.hold) { o.hold = 'chest'; }
      if (pattern === 'squat' && equip === 'cable') o.hold = 'chest';
      return { pattern, equip, hold: h, opts: o, matched: true };
    }
  }
  return { pattern: BY_MUSCLE[ex.primary_muscle] ?? 'squat', equip, opts: {}, matched: false };
}
