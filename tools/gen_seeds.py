"""Generates supabase/migrations/010_seed_exercises.sql and 011_seed_foods.sql
from tools/exercises.txt, tools/food_ar.txt and the CSV. Run: python3 tools/gen_seeds.py"""
import csv, json, re, sys, pathlib
from collections import Counter
here = pathlib.Path(__file__).parent; root = here.parent
q = lambda s: "'" + str(s).replace("'", "''") + "'"
MUSCLES = {'chest','back','shoulders','biceps','triceps','forearms','quads','hamstrings','glutes','calves','abs','traps','full_body','cardio'}
EQUIP = {'barbell','dumbbell','machine','cable','smith','kettlebell','bodyweight','bands','other'}

# ── exercises
rows, seen, errs, cur = [], set(), [], None
for ln, line in enumerate((here / 'exercises.txt').read_text(encoding='utf8').splitlines(), 1):
    line = line.strip()
    if not line: continue
    if line.startswith('## '):
        cur = line[3:]; assert cur in MUSCLES, cur; continue
    eq, en, ar, sec = line.split('|')
    if eq not in EQUIP: errs.append((ln, 'equipment', eq))
    if re.search(r'[A-Za-z]', ar) or not ar: errs.append((ln, 'arabic', ar))
    secs = [s for s in sec.split(',') if s and s != '-']
    errs += [(ln, 'secondary', s) for s in secs if s not in MUSCLES]
    secs = [s for s in dict.fromkeys(secs) if s != cur]
    slug = re.sub(r'[^a-z0-9]+', '-', en.lower()).strip('-')
    if slug in seen: errs.append((ln, 'duplicate', slug)); continue
    seen.add(slug)
    rows.append(dict(slug=slug, name_en=en, name_ar=ar, primary_muscle=cur, secondary_muscles=secs, equipment=eq))
if errs:
    for e in errs: print('ERROR', e)
    sys.exit(1)
vals = []
for r in rows:
    sec = "array[%s]::text[]" % ','.join(map(q, r['secondary_muscles'])) if r['secondary_muscles'] else "'{}'::text[]"
    vals.append(f"({q(r['slug'])},{q(r['name_en'])},{q(r['name_ar'])},{q(r['primary_muscle'])},{sec},{q(r['equipment'])})")
(root / 'supabase/migrations/010_seed_exercises.sql').write_text(
    f"-- Bulkify · 010 · built-in exercise library ({len(rows)} exercises, EN + AR). Generated by tools/gen_seeds.py. Re-runnable.\n"
    "insert into public.bulkify_exercises (slug, name_en, name_ar, primary_muscle, secondary_muscles, equipment) values\n"
    + ',\n'.join(vals) +
    "\non conflict (slug) where owner_id is null do update set name_en = excluded.name_en, name_ar = excluded.name_ar,\n"
    "  primary_muscle = excluded.primary_muscle, secondary_muscles = excluded.secondary_muscles, equipment = excluded.equipment;\n",
    encoding='utf8')
(root / 'supabase/seed/exercises.json').write_text(json.dumps(rows, ensure_ascii=False, indent=1), encoding='utf8')
print(len(rows), 'exercises', dict(Counter(r['primary_muscle'] for r in rows)))

# ── foods
tr = dict(l.split('|', 1) for l in (here / 'food_ar.txt').read_text(encoding='utf8').splitlines() if l.strip())
csv_rows = list(csv.DictReader(open(root / 'supabase/seed/Lebanon_Food_Database_cleaned.csv', encoding='utf8')))
missing = [r['food'] for r in csv_rows if r['food'] not in tr]
if missing: print('MISSING ARABIC', missing); sys.exit(1)
vals, js = [], []
for r in csv_rows:
    d = dict(category_no=int(r['category_no']), category=r['category'], name_en=r['food'], name_ar=tr[r['food']],
             basis_amount=float(r['basis_amount']), basis_unit=r['basis_unit'], kcal=float(r['kcal']),
             protein_g=float(r['protein_g']), carbs_g=float(r['carbs_g']), fat_g=float(r['fat_g']),
             kcal_per_100=float(r['kcal_per_100']), suggested_tag=r['suggested_tag'], note=r['note'].strip())
    assert d['basis_unit'] in ('g', 'ml') and d['suggested_tag'] in ('Everyday', 'Treat')
    js.append(d)
    vals.append("(%d,%s,%s,%s,%g,%s,%g,%g,%g,%g,%g,%s,%s)" % (d['category_no'], q(d['category']), q(d['name_en']), q(d['name_ar']),
        d['basis_amount'], q(d['basis_unit']), d['kcal'], d['protein_g'], d['carbs_g'], d['fat_g'], d['kcal_per_100'], q(d['suggested_tag']), q(d['note'])))
(root / 'supabase/migrations/011_seed_foods.sql').write_text(
    f"-- Bulkify · 011 · food catalog ({len(js)} foods from Lebanon_Food_Database_cleaned.csv + Arabic names). Generated. Re-runnable.\n"
    "insert into public.bulkify_foods (category_no, category, name_en, name_ar, basis_amount, basis_unit, kcal, protein_g, carbs_g, fat_g, kcal_per_100, suggested_tag, note) values\n"
    + ',\n'.join(vals) +
    "\non conflict (category_no, name_en) where owner_id is null do update set category = excluded.category, name_ar = excluded.name_ar,\n"
    "  basis_amount = excluded.basis_amount, basis_unit = excluded.basis_unit, kcal = excluded.kcal, protein_g = excluded.protein_g,\n"
    "  carbs_g = excluded.carbs_g, fat_g = excluded.fat_g, kcal_per_100 = excluded.kcal_per_100,\n"
    "  suggested_tag = excluded.suggested_tag, note = excluded.note;\n", encoding='utf8')
(root / 'supabase/seed/foods.json').write_text(json.dumps(js, ensure_ascii=False), encoding='utf8')
print(len(js), 'foods,', sum(1 for d in js if d['note'] == 'carbs include fibre'), 'with fibre note')
